// TestWriteCSVField verifies the zero-allocation CSV RFC 4180 escaping logic.
// This assumes writeCSVField is defined in export.go (same package).
func TestWriteCSVField(t *testing.T) {
	tests := []struct {
		name     string
		input    []byte
		expected []byte
	}{
		{
			name:     "Empty field",
			input:    []byte(""),
			expected: []byte(""), // Should write nothing, but buffer might act differently
		},
		{
			name:     "Standard field",
			input:    []byte("hello world"),
			expected: []byte("hello world"),
		},
		{
			name:     "Field with comma",
			input:    []byte("hello,world"),
			expected: []byte(`"hello,world"`), // Wrapped in quotes
		},
		{
			name:     "Field with newlines",
			input:    []byte("line1\nline2\rline3"),
			expected: []byte(`"line1` + "\n" + `line2` + "\r" + `line3"`), // Wrapped in quotes
		},
		{
			name:     "Field with quotes",
			input:    []byte(`he said "hello" today`),
			expected: []byte(`"he said ""hello"" today"`), // Wrapped and inner quotes doubled
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var buf bytes.Buffer
			// writeCSVField is internal to package cli, so we can test it here
			err := writeCSVField(&buf, tt.input)
			require.NoError(t, err)

			if len(tt.expected) == 0 {
				assert.Empty(t, buf.Bytes())
			} else {
				assert.Equal(t, tt.expected, buf.Bytes())
			}
		})
	}
}
