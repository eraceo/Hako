// TestLogEvent_EndToEnd verifies the complete logging lifecycle: Event -> JSON -> File.
func TestLogEvent_EndToEnd(t *testing.T) {
	tmpDir := t.TempDir()
	logPath := filepath.Join(tmpDir, "audit.log")
	logger := NewLogger(logPath, true)

	details := map[string]interface{}{
		"user": "testuser",
		"ip":   "192.168.1.1",
	}

	logger.LogEvent(EventVaultInit, true, "Vault initialized", details)

	// Verify file existence and permissions
	info, err := os.Stat(logPath)
	require.NoError(t, err)

	// On Unix, we expect strict 0600 (-rw-------).
	if os.PathSeparator == '/' {
		assert.Equal(t, os.FileMode(0600), info.Mode().Perm())
	}

	// Verify file content
	// #nosec G304 -- Trusted temporary path generated by t.TempDir() for testing purposes
	content, err := os.ReadFile(logPath)
	require.NoError(t, err)

	var event Event
	err = json.Unmarshal(content, &event)
	require.NoError(t, err)

	assert.Equal(t, EventVaultInit, event.EventType)
	assert.True(t, event.Success)
	assert.Equal(t, "Vault initialized", event.Message)
	assert.Equal(t, "testuser", event.Details["user"])
	assert.Equal(t, os.Getpid(), event.ProcessID)
	assert.Equal(t, logger.sessionID, event.SessionID)

	// Verify timestamp is recent (within 5 seconds)
	assert.WithinDuration(t, time.Now().UTC(), event.Timestamp, 5*time.Second)
}

